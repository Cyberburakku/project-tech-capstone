export function getMentorStory(id: string): MentorStory | undefined {
  return mentorStories.find((s) => s.id === id);
}

/** Returns the same story all day, rotating daily by day of year. */
export function getStoryOfTheDay(date = new Date()): MentorStory {
  const today = Date.UTC(date.getFullYear(), date.getMonth(), date.getDate());
  const jan1 = Date.UTC(date.getFullYear(), 0, 1);
  const dayOfYear = Math.round((today - jan1) / 86_400_000);
  return mentorStories[dayOfYear % mentorStories.length] as MentorStory;
}
